export function normalizeAction(action: string): string {
  return (action ?? "")
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "");
}

function clampIntensity(value: unknown): number {
  const n = typeof value === "number" ? value : Number(value);
  if (!Number.isFinite(n)) return 0.6;
  return Math.min(1, Math.max(0, n));
}

export interface ValidatedAiIntent extends AnimationIntentDef {
  /** 0.0 subtle … 1.0 strong (used for crossfade/duration scaling only). */
  intensity: number;
  /** Optional descriptor tags the model may emit (e.g. pose mood selection). */
  tags?: string[];
}

/**
 * Validate an AI-emitted intent against the registry.
 * Returns null for "none", unknown actions, or non-selectable intents —
 * the conversation must never break because of a bad animation decision.
 */
export function validateAiIntent(raw: RawAiIntent | null | undefined): ValidatedAiIntent | null {
  if (!raw || typeof raw !== "object" || typeof raw.action !== "string") return null;

  const normalized = normalizeAction(raw.action);
  if (!normalized) return null;

  const id = ACTION_SYNONYMS[normalized] ?? normalized;
  if (id === "none") return null;

  const def = ANIMATION_INTENTS[id];
  if (!def || !def.aiSelectable) {
    console.warn(`[AiDirector] Rejected unknown animation intent: "${raw.action}"`);
    return null;
  }

  const tags = Array.isArray(raw.tags)
    ? raw.tags.filter((t): t is string => typeof t === "string" && t.length > 0).slice(0, 4)
    : undefined;

  return {
    ...def,
    intensity: clampIntensity(raw.confidence ?? raw.intensity),
    ...(tags && tags.length > 0 ? { tags } : {}),
  };
}

/** Resolve an intent (or a single filename) to a playable URL.
 *  `tags` narrows a tagged pool (generic pose → cute/angry/sad candidates)
 *  before the rotation `pick` is applied. */
export function resolveIntentUrl(
  def: AnimationIntentDef,
  pick: number = 0,
  tags?: string[],
): string | null {
  let files = def.filePool && def.filePool.length > 0 ? def.filePool : [def.file];
  if (def.id === "pose" && tags && tags.length > 0) {
    const tagged = POSE_TAGS.filter((entry) => entry.tags.some((t) => tags.includes(t))).map(
      (entry) => entry.file,
    );
    if (tagged.length > 0) files = tagged;
  }
  if (!files[0]) return null;
  const file = files[pick % files.length];
  if (!file) return null;
  return resolveAnimationUrl(file);
}

/** All dance files for generic dance requests. */
export function getAllDanceUrls(): string[] {
  return ALL_DANCE_FILES.map((name) => resolveAnimationUrl(name)).filter(
    (u): u is string => u !== null,
  );
}
