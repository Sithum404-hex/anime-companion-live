/**
 * animationRegistry.ts — Centralized animation registry for the AI Animation
 * Director. Maps controlled AI intent ids → real .vrma files (verified against
 * public/animations/) with metadata used for arbitration.
 *
 * The AI NEVER names files. It chooses an intent id; the application resolves
 * the intent to a registry entry; only registry-approved files may play.
 */
import type { RawAiIntent } from "./types";
import type { AnimState } from "./controller/AnimationStateMachine";
import { getDanceAnimations, resolveAnimationUrl } from "./vrmAnimationLoader";

export type AiIntentCategory =
  | "emotion"
  | "conversation"
  | "reaction"
  | "movement"
  | "dance"
  | "idle"
  | "none";

export type IntentBehavior = "oneshot" | "loop" | "state";

export interface AnimationIntentDef {
  /** Intent id the AI may choose. */
  id: string;
  /** Exact .vrma filename (no extension) — resolved against the loader pools. */
  file: string | null;
  /** Extra files the intent may pick from (poses, generic dances). */
  filePool?: string[];
  category: AiIntentCategory;
  behavior: IntentBehavior;
  /** Existing state-machine state to request instead of a raw clip. */
  animState?: AnimState;
  /** Arbitration priority: 10 idle · 30 conversational · 50 strong · 90 AI action. */
  priority: number;
  /** Cooldown between plays of this intent (ms). 0 = no cooldown. */
  cooldownMs: number;
  loopable: boolean;
  isDance: boolean;
  /** When dancing, the style pool this intent resolves to. */
  danceStyles?: string[];
  /** Can this intent run while the character is mid-dance? */
  canInterruptDance: boolean;
  /** Whether the AI may select this intent. */
  aiSelectable: boolean;
  /** Human-readable label for the debug panel. */
  label: string;
}

