import { getDanceAnimations } from "./vrmAnimationLoader";

export interface DanceMetadata {
  name: string;
  url: string;
  style: "hiphop" | "breakdance" | "latin" | "other";
  energyMin: number;
  energyMax: number;
  preferredBpmMin: number;
  preferredBpmMax: number;
  intensity: number;
  isLoopable: boolean;
  isTransition: boolean;
  cooldown: number;
}

/** Resolve the URL from the existing animation registry so filenames stay in sync. */
function urlFor(name: string): string {
  const entry = getDanceAnimations().find((e) => e.name === name);
  return entry ? entry.url : `/animations/dance/${encodeURIComponent(name)}.vrma`;
}

